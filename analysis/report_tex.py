"""LaTeX export of the class report (plan 7.4): reports/report.md -> reports/report.tex, for Overleaf.

    python -m analysis.report_tex                 # write reports/report.tex
    python -m analysis.report_tex --check         # fail if reports/report.tex is not what report.md produces
    python -m analysis.report_tex --zip reports/report_overleaf.zip   # also bundle the .tex and its figures

The input is the assembled Markdown (analysis/report.py), so the LaTeX carries the same numbers, tables and citations
and nothing is typed twice. The Markdown subset the report uses: one H1 (title) and a byline line (name · course ·
university · date), Demo/Code lines, H2 sections ("N. Title" numbered by LaTeX in order, Abstract, GenAI
acknowledgement, References), paragraphs with **bold**, *italic*, `code` and bare URLs, pipe tables grouped into one
numbered float by the *Table N.* caption that follows the group (bold panel titles between them), ![figure](path) with
a *Figure N.* caption, one centred formula line, and the IEEE list "[n] ..." which becomes thebibliography; in-text
[n, m] become \\cite so numbers stay linked. Unmapped non-ASCII characters raise, so nothing silently disappears
under pdfLaTeX.
"""

from __future__ import annotations

import argparse
import re
import zipfile
from pathlib import Path

PREAMBLE = r"""\documentclass[11pt,a4paper]{article}
% Generated by analysis/report_tex.py from reports/report.md: edit reports/report_source.md, not this file.
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage{microtype}
\usepackage[a4paper,margin=2.4cm]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{pifont}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{adjustbox}
\usepackage[font=small,labelfont=bf,skip=4pt]{caption}
\usepackage{xcolor}
\usepackage[hidelinks]{hyperref}
\usepackage{url}
\urlstyle{same}
\setlength{\parskip}{4pt}
\setlength{\parindent}{0pt}
\renewcommand{\arraystretch}{1.12}
\newcommand{\panel}[1]{\par\medskip\noindent #1\par\smallskip}
"""

SYMBOLS = {"≥": r"$\geq$", "≤": r"$\leq$", "−": r"$-$", "×": r"$\times$", "✓": r"\checkmark", "✗": r"\ding{55}",
           "·": r"\textperiodcentered{}", "→": r"$\rightarrow$", "≈": r"$\approx$", "…": r"\ldots{}", "°": r"$^\circ$",
           "α": r"$\alpha$", "±": r"$\pm$", "∉": r"$\notin$", "∈": r"$\in$"}
ALLOWED = set("–—‘’“”äéöüàèíóúñçßÄÉÖÜ")  # T1/utf8 handle these as they are
ESCAPES = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
           "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape(text: str) -> str:
    """Plain text -> LaTeX: specials escaped, symbols mapped; anything non-ASCII and unknown raises."""
    out = []
    for ch in text:
        if ch == _LITERAL_STAR:
            out.append("*")
        elif ch in ESCAPES:
            out.append(ESCAPES[ch])
        elif ch in SYMBOLS:
            out.append(SYMBOLS[ch])
        elif ord(ch) > 127 and ch not in ALLOWED:
            raise ValueError(f"no LaTeX mapping for {ch!r} (U+{ord(ch):04X}); add it to SYMBOLS")
        else:
            out.append(ch)
    return "".join(out).replace('"', "''")


_INLINE = re.compile(r"(`[^`]+`|https?://[^\s)\]]+(?<![.,;:])|\*\*.+?\*\*(?!\*)|\*[^*]+\*)")  # bold may hold italics
_CITE = re.compile(r"\[(\d+(?:, \d+)*)\]")


_LITERAL_STAR = "\x00"  # a Markdown-escaped asterisk (\*), kept out of the emphasis matching


def inline(text: str, *, cite: bool = True) -> str:
    """Markdown inline markup -> LaTeX runs; URLs become \\url, [n, m] become \\cite (bibliography keys r<n>)."""
    text = text.replace("\\*", _LITERAL_STAR)
    out = []
    last = 0
    for m in _INLINE.finditer(text):
        out.append(_plain(text[last:m.start()], cite))
        tok = m.group(0)
        if tok.startswith("`"):
            out.append(r"\texttt{" + escape(tok[1:-1]) + "}")
        elif tok.startswith("http"):
            out.append(r"\url{" + tok + "}")
        elif tok.startswith("**"):
            out.append(r"\textbf{" + inline(tok[2:-2], cite=cite) + "}")
        else:
            out.append(r"\emph{" + inline(tok[1:-1], cite=cite) + "}")
        last = m.end()
    out.append(_plain(text[last:], cite))
    return "".join(out)


def _plain(text: str, cite: bool) -> str:
    if not cite:
        return escape(text)
    parts, last = [], 0
    for m in _CITE.finditer(text):
        parts.append(escape(text[last:m.start()]))
        parts.append(r"\cite{" + ",".join(f"r{n.strip()}" for n in m.group(1).split(",")) + "}")
        last = m.end()
    parts.append(escape(text[last:]))
    return "".join(parts)


def _smart_quotes(tex: str) -> str:
    """Straight double quotes (escaped to '' by escape()) -> `` ... '' pairs, paragraph by paragraph."""
    out, open_ = [], True
    i = 0
    while i < len(tex):
        if tex.startswith("''", i):
            out.append("``" if open_ else "''")
            open_ = not open_
            i += 2
        else:
            out.append(tex[i])
            i += 1
    return "".join(out)


def tabular(rows: list[str]) -> str:
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows if not re.match(r"^\|\s*-{3,}", r)]
    ncol = max(len(r) for r in cells)
    spec = "l" * ncol
    lines = [r"\begin{adjustbox}{max width=\linewidth}", r"\begin{tabular}{" + spec + "}", r"\toprule"]
    for i, r in enumerate(cells):
        r = r + [""] * (ncol - len(r))
        lines.append(" & ".join(inline(c, cite=False) for c in r) + r" \\")
        if i == 0:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}"]
    return "\n".join(lines)


def _title_block(lines: list[str], i: int) -> tuple[str, int]:
    """H1 + byline (name · course · university · date) + Demo/Code lines -> \\title, \\author, \\date, links."""
    title = inline(lines[i][2:].strip(), cite=False)
    i += 1
    byline, links = None, []
    while i < len(lines) and not lines[i].startswith("## "):
        s = lines[i].strip()
        if s and byline is None and " · " in s:
            byline = [p.strip() for p in s.split(" · ")]
        elif re.match(r"^\w+: https?://", s):
            links.append(s)
        i += 1
    name, rest = (byline[0], byline[1:-1]) if byline else ("", [])
    date = byline[-1] if byline else ""
    author = escape(name) + "".join(r" \\ " + escape(p) for p in rest)
    head = [r"\title{" + title + "}", r"\author{" + author + "}", r"\date{" + escape(date) + "}", r"\begin{document}", r"\maketitle"]
    if links:
        head += [r"\begin{center}\small"] + [inline(l, cite=False) + (r"\\" if k < len(links) - 1 else "") for k, l in enumerate(links)] + [r"\end{center}"]
    return "\n".join(head), i


def convert(md: str) -> str:
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    lines = md.split("\n")
    body: list[str] = []
    i = 0
    if not lines[0].startswith("# "):
        raise ValueError("the report must start with an H1 title")
    head, i = _title_block(lines, 0)
    body.append(head)
    pending_table: list[str] = []  # panels of the float whose caption has not arrived yet
    pending_figure: str | None = None
    in_abstract = in_bib = False

    def flush_table(caption: str) -> None:
        nonlocal pending_table
        body.append("\n".join([r"\begin{table}[htbp]", r"\centering\small"] + pending_table
                              + [r"\caption{" + inline(caption, cite=False) + "}", r"\end{table}"]))
        pending_table = []

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            i += 1
            continue
        if s.startswith("## "):
            if in_abstract:
                body.append(r"\end{abstract}")
                in_abstract = False
            if in_bib:
                body.append(r"\end{thebibliography}")
                in_bib = False
            name = s[3:].strip()
            if name.lower() == "abstract":
                body.append(r"\begin{abstract}")
                in_abstract = True
            elif name.lower() == "references":
                body.append(r"\begin{thebibliography}{99}" + "\n" + r"\small")  # the environment prints the heading
                in_bib = True
            elif re.match(r"^\d+\. ", name):
                body.append(r"\section{" + inline(name.split(". ", 1)[1], cite=False) + "}")
            else:
                body.append(r"\section*{" + inline(name, cite=False) + "}")
            i += 1
            continue
        if s.startswith("|"):
            block = []
            while i < len(lines) and lines[i].startswith("|"):
                block.append(lines[i])
                i += 1
            pending_table.append(tabular(block))
            continue
        if s.startswith("!["):
            m = re.match(r"!\[[^\]]*\]\(([^)]+)\)", s)
            pending_figure = m.group(1)
            i += 1
            continue
        m = re.match(r"^\*(Table|Figure) \d+\.\s*(.*)\*$", s)
        if m:
            if m.group(1) == "Table":
                if not pending_table:
                    raise ValueError(f"caption without a table: {s[:60]}")
                flush_table(m.group(2))
            else:
                if not pending_figure:
                    raise ValueError(f"caption without a figure: {s[:60]}")
                body.append("\n".join([r"\begin{figure}[htbp]", r"\centering",
                                       r"\includegraphics[width=\linewidth]{" + pending_figure + "}",
                                       r"\caption{" + inline(m.group(2), cite=False) + "}", r"\end{figure}"]))
                pending_figure = None
            i += 1
            continue
        # a paragraph: wrapped lines joined
        buf = [s]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"^(#|\||!\[|\*(Table|Figure) \d|\[\d+\] )", lines[i]):
            buf.append(lines[i].strip())
            i += 1
        text = " ".join(buf)
        if in_bib:
            m = re.match(r"^\[(\d+)\] (.*)$", text)
            if not m:
                raise ValueError(f"reference entry not of the form [n] ...: {text[:60]}")
            body.append(r"\bibitem{r" + m.group(1) + "} " + _smart_quotes(inline(m.group(2), cite=False)))
        elif pending_table:  # a panel title (bold lead) between the tables of one float
            pending_table.append(r"\panel{" + _smart_quotes(inline(text)) + "}")
        elif text.startswith("score("):
            body.append(r"\begin{center}" + "\n" + inline(text) + "\n" + r"\end{center}")
        else:
            body.append(_smart_quotes(inline(text)))
    if pending_table or pending_figure:
        raise ValueError("a table or figure has no caption")
    if in_abstract:
        body.append(r"\end{abstract}")
    if in_bib:
        body.append(r"\end{thebibliography}")
    body.append(r"\end{document}")
    return PREAMBLE + "\n" + "\n\n".join(body) + "\n"


def figures_used(tex: str) -> list[str]:
    return re.findall(r"\\includegraphics\[[^\]]*\]\{([^}]+)\}", tex)


def bundle(tex_path: Path, zip_path: Path) -> list[str]:
    """The .tex and its figures (paths relative to the .tex) in one zip, as Overleaf expects."""
    tex = tex_path.read_text(encoding="utf-8")
    names = ["report.tex" if tex_path.name != "report.tex" else tex_path.name]
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(tex_path, tex_path.name)
        for rel in figures_used(tex):
            z.write(tex_path.parent / rel, rel)
            names.append(rel)
    return names


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default="reports/report.md")
    ap.add_argument("--out", default="reports/report.tex")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from what the source produces")
    ap.add_argument("--zip", help="also write a zip of the .tex and its figures for Overleaf")
    a = ap.parse_args()
    tex = convert(Path(a.source).read_text(encoding="utf-8"))
    out = Path(a.out)
    if a.check:
        same = out.is_file() and out.read_text(encoding="utf-8") == tex
        print("up to date" if same else "STALE: rerun python -m analysis.report_tex")
        raise SystemExit(0 if same else 1)
    out.write_text(tex, encoding="utf-8")
    print(f"wrote {out}")
    if a.zip:
        names = bundle(out, Path(a.zip))
        print(f"wrote {a.zip}: {', '.join(names)}")


if __name__ == "__main__":
    main()
